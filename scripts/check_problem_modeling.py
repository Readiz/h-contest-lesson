def table_after(text: str, marker: str) -> list[list[str]]:
    match = re.search(re.escape(f"<!-- check:{marker} -->") + r"\n((?:\|[^\n]*\n?)+)", text)
    assert match, f"table marker missing: {marker}"
    lines = match.group(1).rstrip("\n").splitlines()
    return [[cell.strip() for cell in line.strip().strip("|").split("|")] for line in lines[2:]]


