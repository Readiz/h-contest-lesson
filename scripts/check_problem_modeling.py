def mutate(code: str, edits: list[tuple[str, str]]) -> str:
    for old, new in edits:
        assert code.count(old) == 1, f"mutation site not unique/found: {old!r}"
        code = code.replace(old, new)
    return code


def summarize_mutant(name: str, lines: list[list[str]]) -> dict:
    if name == "per-machine-division":
        row = pick(lines, "DIFF", "assign")[0]
        return {"answers": row[0], "invalid": row[1], "mismatches": row[2]}
    if name == "naive-assign-baseline":
        return {"invalidSeeds": sum(1 for r in pick(lines, "BASE", "assign") if r[3] == 0),
                "shapes": [[r[0], r[1], r[2], r[3]] for r in pick(lines, "SHAPE", "assign")]}
    if name == "naive-grid-baseline":
        return {"shapes": [[r[0], r[1], r[2], r[3]] for r in pick(lines, "SHAPE", "grid")]}
    if name == "no-reset":
        rows = pick(lines, "SEQ")
        return {"differing": sum(1 for r in rows if (r[1], r[2]) != (r[3], r[4])),
                "invalid": sum(1 for r in rows if r[1] == 0)}
    if name == "grid-bound-t":
        rows = pick(lines, "TINY", "grid446") + pick(lines, "TINY", "grid2020x5")
        cases, mism = pick(lines, "BOUNDREF", "grid")[0]
        return {"boundBelowOptimum": sum(1 for r in rows if r[2] < r[1]), "cases": len(rows),
                "boundRefCases": cases, "boundRefMismatches": mism}
    if name == "assign-bound-no-division-by-m":
        rows = pick(lines, "TINY", "assign633")
        return {"boundAboveOptimum": sum(1 for r in rows if r[2] > r[1]), "cases": len(rows)}
    raise KeyError(name)


# ---------------------------------------------------------------- checks of the lesson code against the oracle
def check_harness(lines: list[list[str]], default: dict, tiny: dict, shapes: dict, seq: list, hand: dict) -> dict:
    result = {}
    cases, mism = pick(lines, "BOUNDREF", "grid")[0]
    assert mism == 0 and cases == 300, "grid bound differs from the independent computation"
    for name in ("route", "assign", "grid"):
        total, invalid, mismatches = pick(lines, "DIFF", name)[0]
        assert mismatches == 0, f"{name}: my score/valid differs from the reference on {mismatches} answers"
        assert 0 < invalid < total
        result[name] = {"answers": total, "invalid": invalid}
    for name in ("route", "assign", "grid"):
        rows = pick(lines, "BASE", name)
        assert len(rows) == len(SEEDS)
        for seed, row in zip(SEEDS, rows):
            _, _, _, valid, score, bound, ratio, refValid, refScore = row
            i = seed - 1
            assert valid == 1 and refValid == 1 and score == refScore, (name, seed, row)
            assert score == default[name]["baseline"][i] and bound == default[name]["bound"][i], (name, seed, row)
            assert ratio == default[name]["ratio1000"][i], (name, seed, row)
    for name in ("route7", "assign633", "grid446", "grid2020x5"):
        rows = pick(lines, "TINY", name)
        assert len(rows) == len(SEEDS)
        for i, (seed, opt, bound, base) in enumerate(rows):
            assert (opt, bound, base) == (tiny[name]["opt"][i], tiny[name]["bound"][i], tiny[name]["baseline"][i]), (name, seed)
    for name, key in (("route", "route"), ("assign", "assign"), ("grid", "grid")):
        rows = pick(lines, "SHAPE", name)
        want = shapes[key]
        assert len(rows) == len(want)
        for row, w in zip(rows, want):
            nparam = len(w) - 1
            assert row[:nparam] == w[:nparam], (name, row, w)
            assert row[3] == row[7] == w[nparam], (name, row, w)
    rows = pick(lines, "SEQ")
    assert len(rows) == len(seq)
    for row, want in zip(rows, seq):
        _, valid, score, refValid, refScore = row
        assert (valid, score) == (refValid, refScore) == tuple(want), (row, want)
    for k, name in enumerate(HAND_CANDIDATES):
        row = pick(lines, "HAND", str(k))[0]
        want = hand["candidates"][name]
        assert row == [want["valid"], want["score"], want["valid"], want["score"]], (name, row, want)
    base = pick(lines, "HANDBASE")[0]
    assert base[0] == 1 and base[1] == hand["candidates"]["first-fit"]["score"] and base[2] == hand["bound"], base
    return result


def run_mutants(blocks: dict[str, str]) -> dict:
    code = lesson_code(blocks)
    jobs = {name: mutate(code, edits) for name, edits in MUTANTS.items()}
    for name, mutated in jobs.items():
        assert mutated != code, name
    with ThreadPoolExecutor(max_workers=4) as pool:
        futures = {name: pool.submit(run_harness_lines, mutated) for name, mutated in jobs.items()}
        return {name: summarize_mutant(name, futures[name].result()) for name in jobs}


