# ---------------------------------------------------------------- lesson text and code
def lesson_blocks(text: str) -> dict[str, str]:
    found = SNIP_RE.findall(text)
    names = [name for name, _ in found]
    assert tuple(names) == BLOCKS, f"snippet blocks must be {BLOCKS} in this order, got {names}"
    return dict(found)


def lesson_code(blocks: dict[str, str]) -> str:
    return "\n".join(blocks[name] for name in BLOCKS) + "\n"


def compile_only(code: str) -> None:
    for name in BLOCKS:
        check_submission_code(code, name)
    with tempfile.TemporaryDirectory(prefix="lesson-model-") as folder:
        src = Path(folder) / "user.cpp"
        src.write_text(code)
        result = subprocess.run(["c++", "-std=c++17", "-Wall", "-Wextra", "-Werror", "-fsyntax-only", str(src)],
                                capture_output=True, text=True)
        assert result.returncode == 0, "header-free compile failed:\n" + result.stderr[-2000:]


def run_harness(code: str, sanitize: bool) -> list[list[str]]:
    flags = SAN if sanitize else ["-O1"]
    with tempfile.TemporaryDirectory(prefix="lesson-model-") as folder:
        src = Path(folder) / "check.cpp"
        exe = Path(folder) / "check"
        src.write_text(HEADERS + code + HARNESS)
        subprocess.run(["c++", "-std=c++17", *flags, str(src), "-o", str(exe)], check=True)
        result = subprocess.run([str(exe)], capture_output=True, text=True, timeout=120)
    assert result.returncode == 0, result.stderr[-2000:]
    lines = [line.split() for line in result.stdout.splitlines()]
    assert lines and lines[-1] == ["HARNESS", "DONE"], "harness did not finish"
    return lines


def pick(lines: list[list[str]], key: str, *rest: str) -> list[list[int]]:
    out = []
    for line in lines:
        if line[0] == key and tuple(line[1:1 + len(rest)]) == rest:
            out.append([int(v) for v in line[1 + len(rest):]])
    return out


