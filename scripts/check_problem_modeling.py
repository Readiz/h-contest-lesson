# ---------------------------------------------------------------- independent Python oracle

MASK = (1 << 64) - 1


class Lcg:
    def __init__(self, seed):
        self.x = seed & MASK

    def below(self, bound):
        self.x = (self.x * 6364136223846793005 + 1442695040888963407) & MASK
        return (self.x >> 33) % bound


def gen_route(seed, n):
    r = Lcg(seed)
    pts = []
    for _ in range(n):
        x = r.below(1000)
        y = r.below(1000)
        pts.append((x, y))
    return pts


def gen_assign(seed, n, m, k):
    r = Lcg(seed)
    d = [1 + r.below(100) for _ in range(n)]
    c = [[r.below(51) for _ in range(m)] for _ in range(n)]
    return {"n": n, "m": m, "k": k, "d": d, "c": c}


def gen_grid(seed, h, w, t):
    r = Lcg(seed)
    v = []
    for _ in range(h):
        row = []
        for _ in range(w):
            u = r.below(10)
            row.append(0 if u < 6 else 1 + r.below(9))
        v.append(row)
    return {"h": h, "w": w, "t": t, "sy": 0, "sx": 0, "v": v}


# ---- reference scores: (valid, score) ----
def route_ref(pts, order):
    n = len(pts)
    if sorted(order) != list(range(n)):
        return False, 0
    return True, sum(abs(pts[a][0] - pts[b][0]) + abs(pts[a][1] - pts[b][1]) for a, b in zip(order, order[1:]))


def assign_ref(cs, machine):
    n, m, k = cs["n"], cs["m"], cs["k"]
    if len(machine) != n or any(not (0 <= q < m) for q in machine):
        return False, 0
    load = [0] * m
    extra = 0
    cnt = [0] * m
    for i, q in enumerate(machine):
        load[q] += cs["d"][i]
        extra += cs["c"][i][q]
        cnt[q] += 1
    if max(cnt) > k:
        return False, 0
    return True, sum(x * x for x in load) // 100 + extra


DIRS = [(-1, 0), (0, 1), (1, 0), (0, -1)]


def grid_ref(cs, dirs):
    y, x = cs["sy"], cs["sx"]
    seen = {(y, x)}
    total = cs["v"][y][x]
    if len(dirs) != cs["t"]:
        return False, 0
    for q in dirs:
        if q not in (0, 1, 2, 3):
            return False, 0
        y += DIRS[q][0]
        x += DIRS[q][1]
        if not (0 <= y < cs["h"] and 0 <= x < cs["w"]):
            return False, 0
        if (y, x) not in seen:
            seen.add((y, x))
            total += cs["v"][y][x]
    return True, total


# ---- baselines ----
def route_baseline(pts):
    return list(range(len(pts)))


def assign_baseline(cs):
    used = [0] * cs["m"]
    out = []
    for _ in range(cs["n"]):
        q = 0
        while q + 1 < cs["m"] and used[q] >= cs["k"]:
            q += 1
        out.append(q)
        used[q] += 1
    return out


def grid_baseline(cs, order=(1, 2, 3, 0)):
    y, x = cs["sy"], cs["sx"]
    out = []
    for _ in range(cs["t"]):
        pick, moved = 0, False
        for q in order:
            ny, nx = y + DIRS[q][0], x + DIRS[q][1]
            if 0 <= ny < cs["h"] and 0 <= nx < cs["w"]:
                pick, moved = q, True
                break
        out.append(pick)
        if moved:
            y += DIRS[pick][0]
            x += DIRS[pick][1]
    return out


# ---- bounds ----
def route_bound(pts):
    n = len(pts)
    edges = sorted((abs(pts[a][0] - pts[b][0]) + abs(pts[a][1] - pts[b][1]), a, b)
                   for a in range(n) for b in range(a + 1, n))
    parent = list(range(n))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    total = 0
    for dist, a, b in edges:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb
            total += dist
    return total


def assign_bound(cs):
    cheapest = sum(min(row) for row in cs["c"])
    total = sum(cs["d"])
    return cheapest + total * total // (100 * cs["m"])


def grid_bound(cs):
    vals = sorted((cs["v"][y][x] for y in range(cs["h"]) for x in range(cs["w"])
                   if abs(y - cs["sy"]) + abs(x - cs["sx"]) <= cs["t"]), reverse=True)
    return sum(vals[:cs["t"] + 1])


# ---- exhaustive optimum for tiny instances ----
def route_opt(pts):
    return min(route_ref(pts, list(p))[1] for p in itertools.permutations(range(len(pts))))


def assign_opt(cs):
    best = None
    for a in itertools.product(range(cs["m"]), repeat=cs["n"]):
        ok, s = assign_ref(cs, list(a))
        if ok and (best is None or s < best):
            best = s
    return best


def grid_opt(cs):
    best = 0
    for a in itertools.product(range(4), repeat=cs["t"]):
        ok, s = grid_ref(cs, list(a))
        if ok and s > best:
            best = s
    return best


